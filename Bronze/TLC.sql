WITH Years AS (
    SELECT 2009 AS Yr UNION ALL SELECT 2010 UNION ALL SELECT 2011 UNION ALL SELECT 2012 UNION ALL 
    SELECT 2013 UNION ALL SELECT 2014 UNION ALL SELECT 2015 UNION ALL SELECT 2016 UNION ALL 
    SELECT 2017 UNION ALL SELECT 2018 UNION ALL SELECT 2019 UNION ALL SELECT 2020 UNION ALL 
    SELECT 2021 UNION ALL SELECT 2022 UNION ALL SELECT 2023 UNION ALL SELECT 2024 UNION ALL 
    SELECT 2025 UNION ALL SELECT 2026
),
Months AS (
    SELECT '01' AS Mth UNION ALL SELECT '02' UNION ALL SELECT '03' UNION ALL 
    SELECT '04' UNION ALL SELECT '05' UNION ALL SELECT '06' UNION ALL 
    SELECT '07' UNION ALL SELECT '08' UNION ALL SELECT '09' UNION ALL 
    SELECT '10' UNION ALL SELECT '11' UNION ALL SELECT '12'
),
Types AS (
    SELECT 'yellow' AS Txt UNION ALL 
    SELECT 'green' UNION ALL 
    SELECT 'fhv' UNION ALL 
    SELECT 'fhvhv'
)
SELECT 
    Txt AS [type],
    CAST(Yr AS VARCHAR(4)) AS [year],
    Mth AS [month]
FROM Types
CROSS JOIN Years
CROSS JOIN Months